#!/usr/bin/env python3
"""
main.py

REST API exposing the warehouse's BI views (analytics.vw_*) for
downstream consumption — dashboards, other services, or ad-hoc scripts
that shouldn't need direct SQL/Redshift access. Reads through
api/db.py, which targets Redshift in production and the local SQLite
demo warehouse (see warehouse/local_demo.py) for local development.

Run locally:
    DATABASE_MODE=local uvicorn api.main:app --reload

Docs: http://localhost:8000/docs (Swagger UI, auto-generated by FastAPI)
"""
from fastapi import FastAPI, HTTPException, Query
from fastapi.middleware.cors import CORSMiddleware

from api.db import run_query, DATABASE_MODE
from api.schemas import CustomerSegment, DailySales, HealthCheck, StorePerformance, TopProduct

app = FastAPI(
    title="Retail Data Warehouse API",
    description="Read-only REST API over the retail sales star schema.",
    version="1.0.0",
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_methods=["GET"],
    allow_headers=["*"],
)


@app.get("/health", response_model=HealthCheck, tags=["meta"])
def health_check():
    return {"status": "ok", "database_mode": DATABASE_MODE}


@app.get("/kpis/daily-sales", response_model=list[DailySales], tags=["kpis"])
def daily_sales(limit: int = Query(30, ge=1, le=365)):
    """Revenue, order count, and margin per day, most recent first."""
    rows = run_query(
        "SELECT * FROM vw_daily_sales ORDER BY full_date DESC LIMIT ?", (limit,)
    )
    return rows


@app.get("/kpis/top-products", response_model=list[TopProduct], tags=["kpis"])
def top_products(limit: int = Query(10, ge=1, le=100)):
    """Best-selling products ranked by net revenue."""
    rows = run_query(
        "SELECT * FROM vw_top_products ORDER BY revenue_rank ASC LIMIT ?", (limit,)
    )
    if not rows:
        raise HTTPException(status_code=404, detail="no product data available")
    return rows


@app.get("/kpis/customer-segments", response_model=list[CustomerSegment], tags=["kpis"])
def customer_segments():
    """Revenue and order volume broken down by customer segment and country."""
    return run_query("SELECT * FROM vw_customer_segments ORDER BY net_revenue DESC")


@app.get("/kpis/store-performance", response_model=list[StorePerformance], tags=["kpis"])
def store_performance(limit: int = Query(20, ge=1, le=100)):
    """Store-level revenue and order counts, highest revenue first."""
    rows = run_query(
        "SELECT * FROM vw_store_performance ORDER BY net_revenue DESC LIMIT ?", (limit,)
    )
    return rows


if __name__ == "__main__":
    import uvicorn
    uvicorn.run("api.main:app", host="0.0.0.0", port=8000, reload=True)
